export function roomMessage(body: string, lang: Lang): string {
  if (lang === 'zh') return body;
  const fixed = roomText(body, lang);
  if (fixed !== body) return fixed;
  for (const [pattern, english] of SYSTEM_MESSAGES) {
    if (pattern.test(body)) return body.replace(pattern, english);
  }
  return body;
}
